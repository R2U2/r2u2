#!/usr/bin/env python3
"""
Ground rewrite rules so that pre terms contain no compound interval bounds.

Compound bounds (addition/subtraction) that appear in a rule's `pre` formula are
replaced with fresh bound variables. The defining relation is either:
  - kept as a constraint (`bN = <expr>`), when the original free variables remain
    grounded by `pre`, or
  - inverted into `post` / other constraints, when a free variable would otherwise
    become ungrounded (appear only on the RHS of the rewrite).

This file was generated by Cursor AI on 2026-11-04.

Usage:
  python3 ground_rewrites.py fret_rewrites.json fret_rewrites_grounded.json
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any


INTERVAL_RE = re.compile(r"\[([^\[\]]*)\]")
BOUND_VAR_RE = re.compile(r"\bb(\d+)\b")
# Atomic bound: variable, mission time, or non-negative integer.
ATOM_RE = re.compile(r"^(?:b\d+|M|\d+)$")
# Binary +/- over atoms, optionally parenthesized. Covers normalize output like b1+1.
COMPOUND_RE = re.compile(
    r"^\(?\s*(b\d+|M|\d+)\s*([+-])\s*(b\d+|M|\d+)\s*\)?$"
)
EQ_CONSTRAINT_RE = re.compile(
    r"^\s*(b\d+)\s*=\s*(.+?)\s*$"
)


def normalize_spaces(expr: str) -> str:
    """Collapse whitespace around arithmetic operators for stable matching."""
    expr = expr.strip()
    expr = re.sub(r"\s*([+-])\s*", r"\1", expr)
    expr = re.sub(r"\s*,\s*", ",", expr)
    return expr


def format_bound(expr: str) -> str:
    """Pretty-print a bound expression for formulas (spaces, parens for compounds)."""
    expr = normalize_spaces(expr)
    m = COMPOUND_RE.match(expr)
    if m:
        return f"({m.group(1)} {m.group(2)} {m.group(3)})"
    return expr


def format_constraint_expr(expr: str) -> str:
    """Pretty-print an arithmetic expression for a constraint RHS."""
    expr = normalize_spaces(expr)
    m = COMPOUND_RE.match(expr)
    if m:
        return f"{m.group(1)} {m.group(2)} {m.group(3)}"
    return expr


def is_compound_bound(bound: str) -> bool:
    """Return True if an interval bound is a compound (+/-) expression."""
    bound = normalize_spaces(bound)
    if ATOM_RE.match(bound):
        return False
    return COMPOUND_RE.match(bound) is not None


def extract_interval_bounds(formula: str) -> list[str]:
    """Return each raw bound string appearing in intervals of `formula`."""
    bounds: list[str] = []
    for match in INTERVAL_RE.finditer(formula):
        body = match.group(1)
        # Split on the top-level comma separating lb and ub.
        depth = 0
        comma_at = -1
        for i, ch in enumerate(body):
            if ch == "(":
                depth += 1
            elif ch == ")":
                depth -= 1
            elif ch == "," and depth == 0:
                comma_at = i
                break
        if comma_at < 0:
            continue
        bounds.append(body[:comma_at].strip())
        bounds.append(body[comma_at + 1 :].strip())
    return bounds


def replace_bounds_in_formula(formula: str, subst: dict[str, str]) -> str:
    """Replace bound expressions inside intervals according to `subst` keys.

    Keys should be normalize_spaces()'d compound (or atom) strings. Longer keys
    are applied first so that e.g. b1+10 is not partially matched by b1+1.
    """
    if not subst:
        return formula

    ordered = sorted(subst.keys(), key=len, reverse=True)

    def rewrite_interval(match: re.Match[str]) -> str:
        body = match.group(1)
        depth = 0
        comma_at = -1
        for i, ch in enumerate(body):
            if ch == "(":
                depth += 1
            elif ch == ")":
                depth -= 1
            elif ch == "," and depth == 0:
                comma_at = i
                break
        if comma_at < 0:
            return match.group(0)

        lb = normalize_spaces(body[:comma_at])
        ub = normalize_spaces(body[comma_at + 1 :])
        for key in ordered:
            if lb == key:
                lb = subst[key]
            if ub == key:
                ub = subst[key]
        return f"[{format_bound(lb)}, {format_bound(ub)}]"

    return INTERVAL_RE.sub(rewrite_interval, formula)


def replace_expr_in_constraint(constraint: str, subst: dict[str, str]) -> str:
    """Replace compound subexpressions in a constraint string."""
    if not subst:
        return constraint
    result = constraint
    for key in sorted(subst.keys(), key=len, reverse=True):
        # Match the compound both with and without surrounding spaces/parens.
        patterns = [
            re.escape(key),
            re.escape(format_constraint_expr(key)),
            re.escape(format_bound(key)),
            re.escape(f"({format_constraint_expr(key)})"),
        ]
        for pat in patterns:
            result = re.sub(pat, subst[key], result)
    return result


def bound_vars_in(*texts: str) -> set[str]:
    """Collect bound-variable names (bN) appearing in the given texts."""
    found: set[str] = set()
    for text in texts:
        found.update(f"b{m}" for m in BOUND_VAR_RE.findall(text))
    return found


def max_bound_index(*texts: str) -> int:
    """Largest N such that bN appears, or -1 if none."""
    indices = [int(m) for text in texts for m in BOUND_VAR_RE.findall(text)]
    return max(indices) if indices else -1


def parse_sum_constraint(constraint: str) -> tuple[str, str, str, str] | None:
    """Parse `bN = bM + c` / `bN = bM - c` (c atom). Returns (lhs, rhs_var, op, atom)."""
    m = EQ_CONSTRAINT_RE.match(constraint)
    if not m:
        return None
    lhs, rhs = m.group(1), normalize_spaces(m.group(2))
    cm = COMPOUND_RE.match(rhs)
    if not cm:
        return None
    left, op, right = cm.group(1), cm.group(2), cm.group(3)
    # Prefer forms where one side is a bound var and the other is an integer/M/var.
    if BOUND_VAR_RE.fullmatch(left):
        return lhs, left, op, right
    if BOUND_VAR_RE.fullmatch(right) and op == "+":
        # bN = c + bM  → treat as bN = bM + c
        return lhs, right, op, left
    return None


def invert_op(op: str) -> str:
    return "-" if op == "+" else "+"


def rewrite_var_as_expr(text: str, var: str, replacement: str) -> str:
    """Replace free occurrences of `var` with `replacement` (already formatted)."""
    return re.sub(rf"\b{re.escape(var)}\b", replacement, text)


def simplify_constraint(constraint: str) -> str:
    """Fold nested +/- of integer constants in equality constraints when possible."""
    m = EQ_CONSTRAINT_RE.match(constraint)
    if not m:
        return constraint
    lhs, rhs = m.group(1), m.group(2).strip()

    # Pattern: (bN +/- k) +/- m  with integer k, m
    nested = re.match(
        r"^\(?\s*(b\d+)\s*([+-])\s*(\d+)\s*\)?\s*([+-])\s*(\d+)\s*$",
        normalize_spaces(rhs),
    )
    if nested:
        var, op1, n1, op2, n2 = nested.groups()
        v1 = int(n1) if op1 == "+" else -int(n1)
        v2 = int(n2) if op2 == "+" else -int(n2)
        total = v1 + v2
        if total == 0:
            return f"{lhs} = {var}"
        if total > 0:
            return f"{lhs} = {var} + {total}"
        return f"{lhs} = {var} - {-total}"

    cm = COMPOUND_RE.match(normalize_spaces(rhs))
    if cm:
        return f"{lhs} = {format_constraint_expr(rhs)}"
    return f"{lhs} = {rhs}"


def ground_rule(rule: dict[str, Any]) -> dict[str, Any]:
    """Return a grounded copy of a single rewrite rule."""
    pre = rule["pre"]
    post = rule["post"]
    constraints = list(rule.get("constraints") or [])
    birewrite = bool(rule.get("birewrite", False))

    # 1) Collect unique compound bounds from pre.
    compounds: list[str] = []
    for bound in extract_interval_bounds(pre):
        key = normalize_spaces(bound)
        if is_compound_bound(key) and key not in compounds:
            compounds.append(key)

    next_idx = max_bound_index(pre, post, *constraints) + 1
    subst: dict[str, str] = {}
    introduced: list[str] = []

    for expr in compounds:
        fresh = f"b{next_idx}"
        next_idx += 1
        subst[expr] = fresh
        introduced.append(f"{fresh} = {format_constraint_expr(expr)}")

    pre = replace_bounds_in_formula(pre, subst)
    post = replace_bounds_in_formula(post, subst)
    constraints = [replace_expr_in_constraint(c, subst) for c in constraints]
    constraints.extend(introduced)

    # 2) Invert equality constraints that leave a variable ungrounded in pre.
    #    Example: pre has b2, constraint `b2 = b1 + 1`, post uses b1
    #    → rewrite post's b1 as (b2 - 1) and drop the constraint.
    while True:
        grounded = bound_vars_in(pre)
        invertible = None
        for i, constraint in enumerate(constraints):
            parsed = parse_sum_constraint(constraint)
            if not parsed:
                continue
            lhs, rhs_var, op, atom = parsed
            if lhs in grounded and rhs_var not in grounded:
                invertible = (i, lhs, rhs_var, op, atom)
                break
        if invertible is None:
            break

        i, lhs, rhs_var, op, atom = invertible
        inv = invert_op(op)
        repl = f"{lhs}{inv}{atom}"
        post = rewrite_var_as_expr(post, rhs_var, format_bound(repl))
        constraints = [
            rewrite_var_as_expr(c, rhs_var, f"({format_constraint_expr(repl)})")
            for j, c in enumerate(constraints)
            if j != i
        ]
        constraints = [simplify_constraint(c) for c in constraints]

        deduped: list[str] = []
        seen: set[str] = set()
        for c in constraints:
            m = EQ_CONSTRAINT_RE.match(c)
            if m and normalize_spaces(m.group(1)) == normalize_spaces(m.group(2)):
                continue
            if c not in seen:
                seen.add(c)
                deduped.append(c)
        constraints = deduped

    # Final sanity: pre must not contain compound bounds.
    leftover = [b for b in extract_interval_bounds(pre) if is_compound_bound(b)]
    if leftover:
        raise ValueError(
            f"Failed to ground pre term; compound bounds remain: {leftover}\n"
            f"  pre: {pre}"
        )

    return {
        "pre": pre,
        "post": post,
        "constraints": constraints,
        "birewrite": birewrite,
    }


def load_rules(data: Any) -> tuple[Any, list[dict[str, Any]], str | None]:
    """
    Load rules from either a category object or a flat list.

    Returns (container_for_rewrite, flat_rules, mode) where mode is
    'dict', 'list', or a category name used only for messaging.
    """
    if isinstance(data, dict):
        rules: list[dict[str, Any]] = []
        for category, category_rules in data.items():
            if not isinstance(category_rules, list):
                raise ValueError(f"Category '{category}' is not a list of rules")
            rules.extend(category_rules)
        return data, rules, "dict"
    if isinstance(data, list):
        return data, data, "list"
    raise ValueError("JSON must be an object of rule categories or a flat rule array")


def ground_document(data: Any) -> Any:
    """Ground every rule in a rewrites.json-style document."""
    if isinstance(data, dict):
        return {
            category: [ground_rule(rule) for rule in category_rules]
            for category, category_rules in data.items()
        }
    if isinstance(data, list):
        return [ground_rule(rule) for rule in data]
    raise ValueError("JSON must be an object of rule categories or a flat rule array")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Ground compound interval bounds in rewrite-rule JSON pre terms."
    )
    parser.add_argument("input_json", type=str, help="Path to input rewrites JSON")
    parser.add_argument(
        "output_json",
        type=str,
        help="Path to write grounded rewrites JSON",
    )
    args = parser.parse_args(argv)

    input_path = Path(args.input_json)
    output_path = Path(args.output_json)

    if not input_path.exists():
        print(f"Error: input file not found: {input_path}", file=sys.stderr)
        return 1

    with open(input_path, encoding="utf-8") as f:
        data = json.load(f)

    try:
        grounded = ground_document(data)
    except ValueError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1

    # Count how many rules changed.
    _, before_rules, _ = load_rules(data)
    _, after_rules, _ = load_rules(grounded)
    changed = sum(1 for a, b in zip(before_rules, after_rules) if a != b)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(grounded, f, indent=4)
        f.write("\n")

    print(f"Grounded {len(after_rules)} rules ({changed} modified) -> {output_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
