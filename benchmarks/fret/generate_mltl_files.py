#!/usr/bin/env python3
"""
Generate .mltl benchmark files from FRET's 288 MLTL formalization templates.

Always writes both trees from the hard-coded JSON sources in this directory:
  - semantics_no_rewrites.json   → mltl/
  - semantics_with_rewrites.json → mltl_with_rewrites/

Instantiation follows IntegratingFRETAndR2U2Analysis/Scripts/comparison_mltl_mem.py:
  - non-M interval sugar (`<=$duration$`, `<$duration$`, …) uses `duration` (N)
  - mission-time bound `M` uses `mission_time`

This file was generated by Cursor AI on 2026-11-07.

Usage (from this directory):
  python3 generate_mltl_files.py
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent

NO_REWRITES_JSON = HERE / "semantics_no_rewrites.json"
WITH_REWRITES_JSON = HERE / "semantics_with_rewrites.json"
NO_REWRITES_OUT = HERE / "mltl"
WITH_REWRITES_OUT = HERE / "mltl_with_rewrites"

# Profiles matching the paper figures: M in {100,1000,10000}, duration N=20.
PROFILES: list[tuple[str, int, int]] = [
    # (dirname, mission_time M, duration N)
    ("M100_N20", 100, 20),
    ("M1000_N20", 1000, 20),
    ("M10000_N20", 10000, 20),
]

# .mltl atomics must be aN (see MLTL lexer). Map FRET placeholders accordingly;
# comparison_mltl_mem.py uses mode/regular/post/stop in .c2po INPUT instead.
PLACEHOLDERS = {
    "$scope_mode$": "a0",
    "$regular_condition$": "a1",
    "$post_condition$": "a2",
    "$stop_condition$": "a3",
}


def instantiate_mltl(formula: str, mission_time: int, duration: int) -> str:
    """Apply the same grounding as comparison_mltl_mem.count_memory (mltl form)."""
    for src, dst in PLACEHOLDERS.items():
        formula = formula.replace(src, dst)

    # Duration sugar must be expanded before bare $duration$ / M replacement.
    formula = formula.replace("<=$duration$+1", f"0,{duration + 1}")
    formula = formula.replace("<=$duration$", f"0,{duration}")
    formula = formula.replace("<$duration$+1", f"0,{duration}")
    formula = formula.replace("<$duration$", f"0,{duration - 1}")
    formula = formula.replace("=$duration$+1", f"{duration + 1},{duration + 1}")
    formula = formula.replace("=$duration$", f"{duration},{duration}")
    formula = formula.replace("(($duration$ + 1) + 1)", f"{duration + 2}")
    formula = formula.replace("($duration$ + 1)", f"{duration + 1}")
    formula = formula.replace("$duration$", str(duration))

    # Mission time: only standalone M (not part of an identifier).
    formula = re.sub(r"\bM\b", str(mission_time), formula)

    formula = formula.replace("TRUE", "true")
    formula = formula.replace("FALSE", "false")
    return formula


def sanitize_key(key: str) -> str:
    """Turn a semantics template key into a filename stem."""
    name = key.strip().lower()
    name = re.sub(r"[^\w]+", "_", name)
    name = re.sub(r"_+", "_", name).strip("_")
    return name


def load_templates(json_path: Path) -> list[tuple[str, str]]:
    data: dict[str, Any] = json.loads(json_path.read_text())
    if not isinstance(data, dict):
        raise ValueError(f"{json_path} must be an object of template entries")
    out: list[tuple[str, str]] = []
    for key, entry in data.items():
        if not isinstance(entry, dict) or "mltlExpanded" not in entry:
            raise ValueError(f"entry {key!r} missing mltlExpanded")
        out.append((key, entry["mltlExpanded"]))
    return out


def generate(json_path: Path, out_root: Path) -> int:
    templates = load_templates(json_path)
    # Clear previous generations so stale profiles do not linger in this out_root.
    if out_root.exists():
        for child in out_root.iterdir():
            if child.is_dir():
                for f in child.glob("*.mltl"):
                    f.unlink()
            elif child.suffix == ".mltl":
                child.unlink()

    n_files = 0
    for profile_name, mission_time, duration in PROFILES:
        profile_dir = out_root / profile_name
        profile_dir.mkdir(parents=True, exist_ok=True)
        used_names: set[str] = set()
        for key, formula in templates:
            stem = sanitize_key(key)
            if stem in used_names:
                raise ValueError(f"duplicate sanitized key: {stem} (from {key})")
            used_names.add(stem)
            instantiated = instantiate_mltl(formula, mission_time, duration)
            remaining = re.findall(r"\$[^$]+\$", instantiated)
            if remaining:
                raise ValueError(
                    f"unsubstituted placeholders in {key}: {remaining}"
                )
            path = profile_dir / f"{stem}.mltl"
            path.write_text(instantiated + "\n")
            n_files += 1
    return n_files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.parse_args(argv)  # accepts -h/--help only

    jobs = [
        (NO_REWRITES_JSON, NO_REWRITES_OUT),
        (WITH_REWRITES_JSON, WITH_REWRITES_OUT),
    ]

    for json_path, out_root in jobs:
        if not json_path.is_file():
            print(f"error: JSON not found: {json_path}", file=sys.stderr)
            return 1
        n_files = generate(json_path, out_root)
        print(
            f"Wrote {n_files} .mltl files under {out_root} "
            f"from {json_path.name} "
            f"({len(PROFILES)} profiles x {n_files // len(PROFILES)} templates)"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
